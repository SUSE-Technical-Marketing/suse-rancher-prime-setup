import * as pulumi from "@pulumi/pulumi";
import { rancherLogin, rancherRequest } from "@lab/kube";

/** How every cloud credential logs in to Rancher, and what it's called there. */
interface Login {
    url: string;
    insecure: boolean;
    username: string;
    password: string;
    /** Display name of the credential. */
    name: string;
}

type Outputs<I> = I & {
    /** `cattle-global-data:cc-xxxxx`, as a provisioning cluster's `cloudCredentialSecretName`. */
    secretName: string;
};

interface Kind<I extends Login> {
    /** The node driver, as Rancher's UI annotates it. */
    driver: string;
    /** The credential's `<driver>credentialConfig` field and its value. */
    config(inputs: I, rancher: { endpoint: { url: string; insecure: boolean }; token: string }): Promise<Record<string, unknown>>;
    /** Inputs that make it another credential. */
    replaces: (keyof I)[];
    /** Inputs whose change updates it: with `put`, the credential's config in Rancher too. */
    updates: (keyof I)[];
    put: boolean;
}

async function login(i: Login) {
    const endpoint = { url: i.url, insecure: i.insecure };
    const token = await rancherLogin(endpoint, i.username, i.password);
    if (!token) throw new Error(`logging in to Rancher at ${i.url} as ${i.username} failed`);
    return { endpoint, token };
}

/** A cloud credential in Rancher of one kind, created and removed the way the UI does it. */
function credentialProvider<I extends Login>(kind: Kind<I>): pulumi.dynamic.ResourceProvider {
    return {
        async create(inputs: I) {
            const rancher = await login(inputs);
            const res = await rancherRequest(rancher.endpoint, "POST", "/v3/cloudcredentials", {
                type: "provisioning.cattle.io/cloud-credential",
                name: inputs.name,
                metadata: { generateName: "cc-", namespace: "fleet-default" },
                annotations: { "provisioning.cattle.io/driver": kind.driver },
                ...(await kind.config(inputs, rancher)),
            }, rancher.token);
            if (res.status !== 201) throw new Error(`creating cloud credential ${inputs.name} failed: HTTP ${res.status} ${JSON.stringify(res.body).slice(0, 300)}`);
            // The API id is `cattle-global-data:cc-xxxxx`, which is also how clusters refer to it.
            return { id: res.body.id, outs: { ...inputs, secretName: res.body.id } };
        },
        async diff(_id: string, olds: Outputs<I>, news: I) {
            const replaces = kind.replaces.filter(k => olds[k] !== news[k]) as string[];
            return { changes: replaces.length > 0 || kind.updates.some(k => olds[k] !== news[k]), replaces };
        },
        async update(id: string, olds: Outputs<I>, news: I) {
            if (kind.put) {
                const rancher = await login(news);
                const current = await rancherRequest(rancher.endpoint, "GET", `/v3/cloudcredentials/${id}`, undefined, rancher.token);
                if (current.status !== 200) throw new Error(`reading cloud credential ${id} failed: HTTP ${current.status}`);
                const res = await rancherRequest(rancher.endpoint, "PUT", `/v3/cloudcredentials/${id}`, { ...current.body, ...(await kind.config(news, rancher)) }, rancher.token);
                if (res.status !== 200) throw new Error(`updating cloud credential ${id} failed: HTTP ${res.status} ${JSON.stringify(res.body).slice(0, 300)}`);
            }
            return { outs: { ...news, secretName: olds.secretName } };
        },
        async delete(id: string, props: Outputs<I>) {
            const rancher = await login(props);
            const res = await rancherRequest(rancher.endpoint, "DELETE", `/v3/cloudcredentials/${id}`, undefined, rancher.token);
            if (res.status >= 300 && res.status !== 404) throw new Error(`deleting cloud credential ${id} failed: HTTP ${res.status}`);
        },
    };
}

interface HarvesterInputs extends Login {
    /** Management cluster id of the imported Harvester. */
    clusterId: string;
}

/**
 * A Harvester cloud credential: a kubeconfig for the imported Harvester generated by Rancher (it
 * goes through Rancher's proxy), stored as the credential.
 */
const harvester = credentialProvider<HarvesterInputs>({
    driver: "harvester",
    async config(inputs, { endpoint, token }) {
        const kc = await rancherRequest(endpoint, "POST", `/v3/clusters/${inputs.clusterId}?action=generateKubeconfig`, {}, token);
        if (kc.status !== 200 || !kc.body?.config) throw new Error(`generating a kubeconfig for ${inputs.clusterId} failed: HTTP ${kc.status}`);
        return { harvestercredentialConfig: { clusterId: inputs.clusterId, clusterType: "imported", kubeconfigContent: kc.body.config } };
    },
    replaces: ["url", "name", "clusterId"],
    updates: ["password", "insecure"],
    put: false,
});

interface Amazonec2Inputs extends Login {
    accessKey: string;
    secretKey: string;
    region: string;
}

/** An Amazon EC2 cloud credential: the site's access keys, for EC2 machines and EKS clusters. */
const amazonec2 = credentialProvider<Amazonec2Inputs>({
    driver: "aws",
    async config(inputs) {
        return { amazonec2credentialConfig: { accessKey: inputs.accessKey, secretKey: inputs.secretKey, defaultRegion: inputs.region } };
    },
    replaces: ["url", "name"],
    updates: ["password", "insecure", "accessKey", "secretKey", "region"],
    put: true,
});

interface RancherLoginArgs {
    url: string;
    insecure: boolean;
    username: string;
    password: pulumi.Input<string>;
    name: string;
}

export interface HarvesterCredentialArgs extends RancherLoginArgs {
    clusterId: pulumi.Input<string>;
}

export class HarvesterCredential extends pulumi.dynamic.Resource {
    declare readonly secretName: pulumi.Output<string>;

    constructor(name: string, args: HarvesterCredentialArgs, opts?: pulumi.CustomResourceOptions) {
        super(harvester, name, { ...args, password: pulumi.secret(args.password), secretName: undefined }, opts, "lab", "HarvesterCredential");
    }
}

export interface Amazonec2CredentialArgs extends RancherLoginArgs {
    accessKey: pulumi.Input<string>;
    secretKey: pulumi.Input<string>;
    region: string;
}

export class Amazonec2Credential extends pulumi.dynamic.Resource {
    declare readonly secretName: pulumi.Output<string>;

    constructor(name: string, args: Amazonec2CredentialArgs, opts?: pulumi.CustomResourceOptions) {
        super(amazonec2, name, {
            ...args,
            password: pulumi.secret(args.password),
            accessKey: pulumi.secret(args.accessKey),
            secretKey: pulumi.secret(args.secretKey),
            secretName: undefined,
        }, opts, "lab", "Amazonec2Credential");
    }
}
