import * as pulumi from "@pulumi/pulumi";
import { rancherLogin, rancherRequest } from "@lab/kube";

interface Inputs {
    url: string;
    insecure: boolean;
    username: string;
    password: string;
    /** Display name of the credential. */
    name: string;
    /** Management cluster id of the imported Harvester. */
    clusterId: string;
}

interface Outputs extends Inputs {
    /** `cattle-global-data:cc-xxxxx`, as a provisioning cluster's `cloudCredentialSecretName`. */
    secretName: string;
}

/**
 * A Harvester cloud credential in Rancher, the way the UI makes one: a kubeconfig for the imported
 * Harvester generated by Rancher (it goes through Rancher's proxy), stored as the credential.
 */
const provider: pulumi.dynamic.ResourceProvider = {
    async create(inputs: Inputs) {
        const endpoint = { url: inputs.url, insecure: inputs.insecure };
        const token = await rancherLogin(endpoint, inputs.username, inputs.password);
        if (!token) throw new Error(`logging in to Rancher at ${inputs.url} as ${inputs.username} failed`);
        const kc = await rancherRequest(endpoint, "POST", `/v3/clusters/${inputs.clusterId}?action=generateKubeconfig`, {}, token);
        if (kc.status !== 200 || !kc.body?.config) throw new Error(`generating a kubeconfig for ${inputs.clusterId} failed: HTTP ${kc.status}`);
        const res = await rancherRequest(endpoint, "POST", "/v3/cloudcredentials", {
            type: "provisioning.cattle.io/cloud-credential",
            name: inputs.name,
            metadata: { generateName: "cc-", namespace: "fleet-default" },
            annotations: { "provisioning.cattle.io/driver": "harvester" },
            harvestercredentialConfig: { clusterId: inputs.clusterId, clusterType: "imported", kubeconfigContent: kc.body.config },
        }, token);
        if (res.status !== 201) throw new Error(`creating cloud credential ${inputs.name} failed: HTTP ${res.status} ${JSON.stringify(res.body).slice(0, 300)}`);
        // The API id is `cattle-global-data:cc-xxxxx`, which is also how clusters refer to it.
        return { id: res.body.id, outs: { ...inputs, secretName: res.body.id } };
    },
    async diff(_id: string, olds: Outputs, news: Inputs) {
        const replaces = (["url", "name", "clusterId"] as const).filter(k => olds[k] !== news[k]);
        return { changes: replaces.length > 0 || olds.password !== news.password || olds.insecure !== news.insecure, replaces };
    },
    async update(_id: string, olds: Outputs, news: Inputs) {
        return { outs: { ...news, secretName: olds.secretName } };
    },
    async delete(id: string, props: Outputs) {
        const endpoint = { url: props.url, insecure: props.insecure };
        const token = await rancherLogin(endpoint, props.username, props.password);
        if (!token) throw new Error(`logging in to Rancher at ${props.url} as ${props.username} failed`);
        const res = await rancherRequest(endpoint, "DELETE", `/v3/cloudcredentials/${id}`, undefined, token);
        if (res.status >= 300 && res.status !== 404) throw new Error(`deleting cloud credential ${id} failed: HTTP ${res.status}`);
    },
};

export interface HarvesterCredentialArgs {
    url: string;
    insecure: boolean;
    username: string;
    password: pulumi.Input<string>;
    name: string;
    clusterId: pulumi.Input<string>;
}

export class HarvesterCredential extends pulumi.dynamic.Resource {
    declare readonly secretName: pulumi.Output<string>;

    constructor(name: string, args: HarvesterCredentialArgs, opts?: pulumi.CustomResourceOptions) {
        super(provider, name, { ...args, password: pulumi.secret(args.password), secretName: undefined }, opts, "lab", "HarvesterCredential");
    }
}
